"""Build reproducible developer and browser-store submission packages."""
from pathlib import Path
import hashlib
import json
import zipfile

root = Path(__file__).resolve().parent.parent
source = root / 'companion'
out = root / 'public/downloads/Scout-Companion.zip'
out.parent.mkdir(parents=True, exist_ok=True)
manifest = json.loads((source / 'manifest.json').read_text())
guide = json.loads((root / 'lib/companion-guide.json').read_text())
manual = guide['title'] + '\nVersion ' + manifest['version'] + '\nhttps://nextrole-scout.vercel.app/extension\n\n' + guide['intro'] + '\n\n'
manual += '\n\n'.join(str(i + 1) + '. ' + step['title'].upper() + '\n' + step['body'] for i, step in enumerate(guide['steps']))
manual += '\n\nTROUBLESHOOTING\n\n' + '\n\n'.join(item['title'] + '\n' + item['body'] for item in guide['troubleshooting']) + '\n'
(source / 'SETUP.txt').write_text(manual)
(out.parent / 'Scout-Companion-Setup.txt').write_text(manual)
assert manifest['manifest_version'] == 3
assert '<all_urls>' not in json.dumps(manifest)
with zipfile.ZipFile(out, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for path in sorted(source.rglob('*')):
        if not path.is_file() or path.is_symlink() or path.suffix not in {'.json', '.js', '.mjs', '.html', '.css', '.md', '.txt', '.png'}:
            continue
        entry = zipfile.ZipInfo(path.relative_to(source).as_posix(), date_time=(2026, 1, 1, 0, 0, 0))
        entry.compress_type = zipfile.ZIP_DEFLATED
        entry.external_attr = 0o100644 << 16
        archive.writestr(entry, path.read_bytes())
with zipfile.ZipFile(out) as archive:
    assert archive.testzip() is None
    assert 'manifest.json' in archive.namelist()
    assert 'SETUP.txt' in archive.namelist()
store_out = root / 'handoff/store/Scout-Companion-Store.zip'
store_out.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(out) as dev, zipfile.ZipFile(store_out, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as store:
    for name in dev.namelist():
        if name.endswith(('.md', '.txt')):
            continue
        entry = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
        entry.compress_type = zipfile.ZIP_DEFLATED
        entry.external_attr = 0o100644 << 16
        store.writestr(entry, dev.read(name))
release = {'version':manifest['version'],'bytes':out.stat().st_size,'sha256':hashlib.sha256(out.read_bytes()).hexdigest(),'minimumChromeVersion':manifest['minimum_chrome_version'],'download':'/downloads/Scout-Companion.zip','guide':'/downloads/Scout-Companion-Setup.txt'}
(root / 'lib/companion-release.ts').write_text('// Generated by scripts/package-companion.py; keep in sync with the ZIP.\nexport const companionRelease = '+json.dumps(release,indent=2)+' as const;\n')
print(json.dumps({'file':str(out),**release}))
